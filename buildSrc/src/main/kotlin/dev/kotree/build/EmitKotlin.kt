package dev.kotree.build

/** Package and file of the generated Kotlin, relative to the output source root. */
const val GENERATED_PACKAGE: String = "dev.kotree.site.tree.model"
const val GENERATED_FILE_PATH: String = "dev/kotree/site/tree/model/GeneratedTreeData.kt"

/** Escapes for a Kotlin string literal: `\`, `"`, `$`, control characters and every non-ASCII char. */
internal fun kotlinString(s: String): String {
    val sb = StringBuilder(s.length + 2)
    sb.append('"')
    for (ch in s) {
        when {
            ch == '\\' -> sb.append("\\\\")
            ch == '"' -> sb.append("\\\"")
            ch == '$' -> sb.append("\\$")
            ch == '\n' -> sb.append("\\n")
            ch == '\r' -> sb.append("\\r")
            ch == '\t' -> sb.append("\\t")
            ch.code < 0x20 || ch.code > 0x7E -> sb.append("\\u").append(ch.code.toString(16).padStart(4, '0'))
            else -> sb.append(ch)
        }
    }
    sb.append('"')
    return sb.toString()
}

private fun kString(s: String?): String = if (s == null) "null" else kotlinString(s)

private fun kCounts(c: TreeCounts): String = "Counts(live = ${c.live}, total = ${c.total})"

private fun branchFn(i: Int): String = "branch" + i.toString().padStart(2, '0')

/** The whole generated file as a string: `\n` line endings, no timestamps, schema order. */
fun emitKotlin(t: TreeModel): String {
    val sb = StringBuilder(512 * 1024)
    sb.append("// Generated by the generateTreeData Gradle task from /content. Do not edit.\n")
    sb.append("package ").append(GENERATED_PACKAGE).append("\n\n")
    sb.append("val treeData: TreeData = TreeData(\n")
    sb.append("    schema = ").append(t.schema).append(",\n")
    sb.append("    seed = ").append(t.seed).append("L,\n")
    sb.append("    startHere = ").append(kotlinString(t.startHere)).append(",\n")
    sb.append("    counts = ").append(kCounts(t.counts)).append(",\n")
    sb.append("    boughs = listOf(\n")
    var idx = 0
    for (b in t.boughs) {
        sb.append("        Bough(\n")
        sb.append("            id = ").append(kotlinString(b.id)).append(",\n")
        sb.append("            title = ").append(kotlinString(b.title)).append(",\n")
        sb.append("            order = ").append(b.order).append(",\n")
        sb.append("            branches = listOf(")
        sb.append(b.branches.joinToString(", ") { branchFn(idx++) + "()" })
        sb.append("),\n")
        sb.append("        ),\n")
    }
    sb.append("    ),\n)\n")

    idx = 0
    for (b in t.boughs) for (br in b.branches) {
        sb.append("\nprivate fun ").append(branchFn(idx++)).append("(): Branch = Branch(\n")
        sb.append("    id = ").append(kotlinString(br.id)).append(",\n")
        sb.append("    title = ").append(kotlinString(br.title)).append(",\n")
        sb.append("    order = ").append(br.order).append(",\n")
        sb.append("    accent = ").append(kotlinString(br.accent)).append(",\n")
        sb.append("    counts = ").append(kCounts(br.counts)).append(",\n")
        sb.append("    upNext = ").append(kString(br.upNext)).append(",\n")
        sb.append("    stems = listOf(\n")
        for (s in br.stems) {
            sb.append("        Stem(\n")
            sb.append("            id = ").append(kotlinString(s.id)).append(",\n")
            sb.append("            slug = ").append(kotlinString(s.slug)).append(",\n")
            sb.append("            title = ").append(kotlinString(s.title)).append(",\n")
            sb.append("            why = ").append(kotlinString(s.why)).append(",\n")
            sb.append("            order = ").append(s.order).append(",\n")
            sb.append("            counts = ").append(kCounts(s.counts)).append(",\n")
            sb.append("            leaves = listOf(\n")
            for (l in s.leaves) {
                sb.append("                Leaf(")
                sb.append("id = ").append(kotlinString(l.id))
                sb.append(", slug = ").append(kotlinString(l.slug))
                sb.append(", title = ").append(kotlinString(l.title))
                sb.append(", status = LeafStatus.").append(l.status.uppercase())
                sb.append(", difficulty = Difficulty.").append(l.difficulty.uppercase())
                sb.append(", order = ").append(l.order)
                sb.append(", requires = ")
                sb.append(if (l.requires.isEmpty()) "emptyList()" else l.requires.joinToString(", ", "listOf(", ")") { kotlinString(it) })
                sb.append(", fruit = ").append(l.fruit)
                sb.append(", path = ").append(kString(l.path))
                sb.append(", summary = ").append(kString(l.summary))
                sb.append(", video = ").append(kString(l.video))
                sb.append(", publishedOn = ").append(kString(l.publishedOn))
                sb.append("),\n")
            }
            sb.append("            ),\n")
            sb.append("        ),\n")
        }
        sb.append("    ),\n)\n")
    }
    return sb.toString()
}
