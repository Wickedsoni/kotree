#!/usr/bin/env python3
"""Regenerate PROGRESS.md from site/build/tree.json (docs/03 section 4.2).

Stdlib only. Run from anywhere:  python scripts/progress.py
Exit 0 = PROGRESS.md written. Exit 1 = tree.json missing or unreadable; PROGRESS.md is left unchanged.
"""

import datetime
import json
import os
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
TREE = os.path.join(REPO, "site", "build", "tree.json")
OUT = os.path.join(REPO, "PROGRESS.md")


def fail(msg):
    print("progress.py: " + msg, file=sys.stderr)
    print("progress.py: PROGRESS.md was not changed.", file=sys.stderr)
    sys.exit(1)


def load_tree(path):
    if not os.path.isfile(path):
        fail(
            "site/build/tree.json not found at " + path + ". "
            "Run the Kobweb build that includes generateTreeData and copyTreeJson "
            "(locally: ../gradlew :site:copyTreeJson from /site), then rerun this script."
        )
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError) as e:
        fail("tree.json could not be read: " + str(e))


def collect(tree):
    """Return (branch rows, all leaves). Each row: dict with id, title, live, total, upNext, boughTitle."""
    rows = []
    leaves = []
    for bough in tree.get("boughs", []):
        for br in bough.get("branches", []):
            live = 0
            total = 0
            for stem in br.get("stems", []):
                for leaf in stem.get("leaves", []):
                    total += 1
                    if leaf.get("status") == "live":
                        live += 1
                        leaves.append(leaf)
            rows.append({
                "id": br.get("id", "?"),
                "title": br.get("title", br.get("id", "?")),
                "live": live,
                "total": total,
                "upNext": br.get("upNext"),
            })
    return rows, leaves


def pct(part, whole):
    return "0.0" if whole == 0 else "%.1f" % (100.0 * part / whole)


def render(tree, rows, live_leaves):
    counts = tree.get("counts", {})
    live = counts.get("live", sum(r["live"] for r in rows))
    total = counts.get("total", sum(r["total"] for r in rows))
    today = datetime.date.today()
    cutoff = today - datetime.timedelta(days=7)

    out = []
    out.append("# Kotree progress")
    out.append("")
    out.append("> Generated by `scripts/progress.py` from `site/build/tree.json`. Do not edit by hand; rerun the script.")
    out.append("")
    out.append("**%d of %d leaves live (%s%%).**" % (live, total, pct(live, total)))
    out.append("")
    out.append("| Branch | Live | Total | % | Up next |")
    out.append("|---|---:|---:|---:|---|")
    for r in rows:
        up = "complete" if r["upNext"] is None else "`" + r["upNext"] + "`"
        out.append("| %s | %d | %d | %s | %s |" % (r["id"], r["live"], r["total"], pct(r["live"], r["total"]), up))
    out.append("| **All** | **%d** | **%d** | **%s** | |" % (live, total, pct(live, total)))
    out.append("")
    out.append("## Up next")
    out.append("")
    ups = [r for r in rows if r["upNext"] is not None]
    if not ups:
        out.append("- None. Every branch is complete or has no leaves yet.")
    for r in ups:
        out.append("- %s: `%s`" % (r["id"], r["upNext"]))
    out.append("")
    out.append("## Last 7 days")
    out.append("")
    recent = []
    for leaf in live_leaves:
        d = leaf.get("publishedOn")
        try:
            when = datetime.date.fromisoformat(d) if d else None
        except ValueError:
            when = None
        if when is not None and when >= cutoff:
            recent.append((when, leaf))
    recent.sort(key=lambda t: (t[0], t[1].get("id", "")), reverse=True)
    if not recent:
        out.append("- No leaves published in the last 7 days.")
    for when, leaf in recent:
        out.append("- %s: `%s` %s" % (when.isoformat(), leaf.get("id", "?"), leaf.get("title", "")))
    out.append("")
    out.append("_Counts as of %s._" % today.isoformat())
    out.append("")
    return "\n".join(out)


def main():
    tree = load_tree(TREE)
    rows, live_leaves = collect(tree)
    text = render(tree, rows, live_leaves)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("progress.py: wrote " + OUT)


if __name__ == "__main__":
    main()
